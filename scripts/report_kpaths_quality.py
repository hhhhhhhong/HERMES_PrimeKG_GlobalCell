"""Separate target-anchored routes from disease context; no model or labels.

This audit classifies *retrieved graph evidence*, not true synergy mechanisms.
Every reported fact is independently checked against its original CSV row.
"""
import argparse
from collections import Counter
import csv
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from global_cell.common import read, write, sha


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--audit', type=Path, required=True)
    args = parser.parse_args()
    folder = args.audit.resolve()
    assert str(folder).startswith(str(ROOT) + '/')
    audit = read(folder / 'AUDIT.json')
    assert audit['status'] == 'passed'
    queries = {d: [json.loads(s) for s in (folder / (d + '_paths.jsonl')).read_text().splitlines()]
               for d in audit['datasets']}
    used = {f for qs in queries.values() for q in qs for method in ['reference', 'adapted']
            for p in q[method]['paths'] + q[method]['fallback'] for f in p['fact_ids']}
    with (folder / 'index_facts.jsonl').open() as stream:
        facts = {i: json.loads(s) for i, s in enumerate(stream) if i in used}
    # Independent replay of source rows, rather than comparing two copies of
    # fields generated by the retriever. First representative of duplicate facts
    # is intentionally retained; this does not imply independent corroboration.
    expected = {f['row']: f for f in facts.values()}
    checked = set()
    raw = ROOT.parent / 'HERMES_PrimeKG_HHNN/data/raw/edges.csv'
    assert sha(raw) == read(folder / 'INDEX.json')['raw_sha256']['edges.csv']
    with raw.open() as stream:
        for row_id, row in enumerate(csv.DictReader(stream)):
            if row_id in expected:
                f = expected[row_id]
                assert [int(row['x_index']), int(row['y_index'])] == [f['raw_x'], f['raw_y']]
                assert row['relation'] == f['raw_relation']
                if row['relation'] == 'drug_protein':
                    assert f['family'] == 'drug_' + row['display_relation']
                checked.add(row_id)
    assert checked == set(expected)
    nodes = read(folder / 'index_nodes.json')

    def kind(path):
        if path['family'] == 'disease':
            return 'disease_association_context'
        if all(facts[i]['family'] == 'drug_target' for i in (path['fact_ids'][0], path['fact_ids'][-1])):
            return 'target_anchored_candidate'
        return 'other_protein_association_context'

    def example(q, p):
        return dict(drugs=q['drug_names'], family=p['family'], evidence_class=kind(p),
            entities=[nodes[str(v)]['node_name'] for v in p['entities']],
            relations=p['relations'], roles=p['roles'], source_rows=p['source_rows'],
            biological_causality_claim=False)

    results = {}
    for dataset, qs in queries.items():
        methods = {}
        for method in ['reference', 'adapted']:
            paths = [p for q in qs for p in q[method]['paths']]
            examples = {}
            for q in qs:
                ps = q[method]['paths']
                assert len(ps) <= 10
                assert max(Counter(tuple(p['relations']) for p in ps).values(), default=0) <= (1 if method=='reference' else 2)
                for p in ps:
                    if p['hops'] == 4:
                        assert method == 'adapted' and p['family'] in {'go', 'pathway'}
                        assert kind(p) == 'target_anchored_candidate'
                    else:
                        assert p['hops'] <= 3
                    examples.setdefault(p['family'] + ':' + kind(p), example(q, p))
            methods[method] = dict(path_counts=dict(Counter(kind(p) for p in paths)),
                queries_with_target_anchored_candidates=sum(any(kind(p)=='target_anchored_candidate'
                    for p in q[method]['paths']) for q in qs),
                queries_with_only_disease_paths=sum(bool(q[method]['paths']) and all(kind(p)=='disease_association_context'
                    for p in q[method]['paths']) for q in qs),
                queries_with_GO_or_Reactome=sum(any(p['family'] in {'go','pathway'} for p in q[method]['paths']) for q in qs),
                query_indices_with_censored_search=[q['drug_indices'] for q in qs if q[method]['censored']],
                examples=list(examples.values()))
        results[dataset] = methods
    write(folder / 'QUALITY.json', dict(status='passed', datasets=results,
        unique_used_facts=len(facts), independently_verified_raw_rows=len(checked),
        route_limits_and_pattern_diversity_verified=True, source_sha256=sha(__file__),
        label_free=True, quality_is_not_experimental_mechanism_validation=True,
        scope='Same sampled pairs as AUDIT.json; no additional retrieval or training'))
    print(json.dumps(dict(status='passed', verified_raw_rows=len(checked), datasets={d:{m:{k:v for k,v in s.items() if k!='examples'}
        for m,s in methods.items()} for d,methods in results.items()}), indent=2))


if __name__ == '__main__':
    main()
